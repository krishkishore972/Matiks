export const WEND_WORDS: string[] = [
  ...FOUR_LETTER_WORDS,
  ...FIVE_LETTER_WORDS,
  ...SIX_LETTER_WORDS,
];

export interface WendWord {
  word: string;
  path: number[];
}

export interface WendPuzzle {
  id: string;
  seed: string;
  size: number;
  letters: string[];
  words: WendWord[];
}

const SIZES = [5, 6];

function neighbours(size: number, cell: number): number[] {
  const row = Math.floor(cell / size);
  const col = cell % size;
  const out: number[] = [];
  if (row > 0) out.push(cell - size);
  if (row < size - 1) out.push(cell + size);
  if (col > 0) out.push(cell - 1);
  if (col < size - 1) out.push(cell + 1);
  return out;
}

function placeWord(
  size: number,
  word: string,
  used: Set<number>,
  rng: ReturnType<typeof createRng>,
): number[] | null {
  const total = size * size;
  for (let attempt = 0; attempt < 250; attempt++) {
    const start = rng.int(total);
    if (used.has(start)) continue;
    const path = [start];
    const localUsed = new Set<number>([start]);
    let ok = true;
    for (let i = 1; i < word.length; i++) {
      const options = neighbours(size, path[i - 1]).filter(
        (cell) => !used.has(cell) && !localUsed.has(cell),
      );
      if (options.length === 0) {
        ok = false;
        break;
      }
      const next = rng.pick(options);
      path.push(next);
      localUsed.add(next);
    }
    if (ok) return path;
  }
  return null;
}

export function generateWend(seed: string | number, sizeOverride?: number): WendPuzzle {
  const baseRng = createRng(seed);
  const size = sizeOverride ?? baseRng.pick(SIZES);

  for (let attempt = 0; attempt < 120; attempt++) {
    const rng = createRng(`${seed}:${attempt}`);
    const letters = new Array<string>(size * size).fill("");
    const used = new Set<number>();
    const words: WendWord[] = [];
    const wantedLengths = size === 5 ? [4, 4, 5, 5] : [4, 5, 5, 6, 6];

    const pool = rng.shuffle(WEND_WORDS.filter((w) => wantedLengths.includes(w.length)));
    let cursor = 0;
    for (const length of wantedLengths) {
      let placed = false;
      for (let i = 0; i < pool.length; i++) {
        const word = pool[(cursor + i) % pool.length];
        if (word.length !== length || words.some((w) => w.word === word)) continue;
        const path = placeWord(size, word, used, rng);
        if (!path) continue;
        for (const cell of path) used.add(cell);
        path.forEach((cell, index) => {
          letters[cell] = word[index];
        });
        words.push({ word, path });
        cursor = (cursor + i + 1) % pool.length;
        placed = true;
        break;
      }
      if (!placed) break;
    }

    if (words.length !== wantedLengths.length) continue;

    const alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZ";
    for (let cell = 0; cell < letters.length; cell++) {
      if (!letters[cell]) letters[cell] = alphabet[rng.int(alphabet.length)];
    }

    return { id: `wend-${size}-${String(seed)}`, seed: String(seed), size, letters, words };
  }

  throw new Error("wend generation failed");
}

/** Word lengths are shown to the player as the only hint, per the reference. */
export function wendLengthHint(puzzle: WendPuzzle): number[] {
  return puzzle.words.map((w) => w.word.length).sort((a, b) => a - b);
}

export function lettersAlong(puzzle: WendPuzzle, path: number[]): string {
  return path.map((cell) => puzzle.letters[cell] ?? "").join("");
}

export interface WendValidation {
  solved: boolean;
  found: string[];
  invalid: number[];
}

/**
 * Validate traced paths. A trace must be contiguous (adjacent cells, no
 * repeats) and spell one of the board's words.
 */
export function validateWend(puzzle: WendPuzzle, traces: number[][]): WendValidation {
  const targets = new Set(puzzle.words.map((w) => w.word));
  const found = new Set<string>();
  const invalid: number[] = [];

  traces.forEach((path, traceIndex) => {
    const seen = new Set<number>();
    let contiguous = path.length > 1;
    for (let i = 0; i < path.length; i++) {
      if (seen.has(path[i])) contiguous = false;
      seen.add(path[i]);
      if (i > 0 && !neighbours(puzzle.size, path[i - 1]).includes(path[i])) contiguous = false;
    }
    const word = lettersAlong(puzzle, path);
    if (!contiguous || !targets.has(word) || found.has(word)) invalid.push(traceIndex);
    else found.add(word);
  });

  return { solved: found.size === puzzle.words.length, found: [...found], invalid };
}
